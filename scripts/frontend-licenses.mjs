import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(await readFile(join(root, 'package-lock.json'), 'utf8'));
// Also retain the build tools' notices for helpers emitted into production assets.
const helpers = new Set(['node_modules/vite', 'node_modules/rolldown', 'node_modules/@oxc-project/runtime', 'node_modules/@rolldown/runtime']);
const packages = Object.entries(lock.packages).filter(([path, info]) => path && (!info.dev || helpers.has(path))).sort(([a], [b]) => a.localeCompare(b));
const sections = ['Frontend third-party licenses / 前端第三方许可证', '', 'Complete notices for locked runtime dependencies and production build helpers.', 'Generated by scripts/frontend-licenses.mjs; original license text is retained below.', ''];
for (const [path, info] of packages) {
  if (!/^node_modules\/(?:@[^/]+\/)?[^/]+$/.test(path)) throw new Error(`Unexpected dependency path: ${path}`);
  const directory = join(root, path);
  const installed = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  if (installed.version !== info.version) throw new Error(`Installed version differs from lock: ${installed.name}`);
  const names = (await readdir(directory)).filter(name => /^(?:third[-_]party[-_])?(?:licenses?|licences?|copying|notices?)(\.|$)/i.test(name)).sort();
  if (!names.length) throw new Error(`Missing license text: ${installed.name}`);
  sections.push('='.repeat(72), `${installed.name}@${info.version} (${info.license || installed.license || 'see original text'})`, '');
  for (const name of names) sections.push(`--- ${name} ---`, await readFile(join(directory, name), 'utf8'), '');
}
const content = sections.join('\n');
await mkdir(join(root, 'docs'), { recursive: true });
await writeFile(join(root, 'docs', 'frontend-licenses.txt'), content);
await writeFile(join(root, 'dist', 'third-party-licenses.txt'), content);
console.log(`Retained complete license text for ${packages.length} frontend dependencies/helpers.`);
